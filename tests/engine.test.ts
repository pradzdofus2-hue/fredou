test('idempotent seed reapplies central configuration without altering past ledger',()=>{
  const db=database.getDb(),before=engine.getState('fredou');
  db.prepare("UPDATE cards SET recycle_value=999,collection_points=999 WHERE id='card-1'").run();
  db.prepare("UPDATE boosters SET pity_limit=1 WHERE id='free'").run();
  database.seed(db);
  const afterState=engine.getState('fredou');
  assert.equal(afterState.cards.find(c=>c.id==='card-1')!.recycleValue,1);
  assert.equal(afterState.cards.find(c=>c.id==='card-1')!.collectionPoints,1);
  assert.equal(afterState.boosters.find(b=>b.id==='free')!.pityLimit,250);
  assert.deepEqual(afterState.ledger,before.ledger);
  assert.deepEqual(afterState.inventory,before.inventory);
});
